const dicts: Record<Lang, Dict> = { en, hi, gu, mr, bn };

type Ctx = {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (key: string) => string;
  speak: (text: string) => void;
  stop: () => void;
  speaking: boolean;
  voiceCode: string;
};

const I18nContext = createContext<Ctx | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>("en");
  const [speaking, setSpeaking] = useState(false);

  const voiceCode = languages.find((l) => l.code === lang)?.voice ?? "en-IN";

  useEffect(() => {
    const saved = window.localStorage.getItem("cc-lang") as Lang | null;
    if (saved && dicts[saved]) setLangState(saved);
  }, []);

  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    window.localStorage.setItem("cc-lang", l);
    if (typeof window !== "undefined" && "speechSynthesis" in window) {
      window.speechSynthesis.cancel();
    }
  }, []);

  const t = useCallback((key: string) => dicts[lang][key] ?? en[key] ?? key, [lang]);

  const stop = useCallback(() => {
    if (typeof window === "undefined" || !("speechSynthesis" in window)) return;
    window.speechSynthesis.cancel();
    setSpeaking(false);
  }, []);

  const speak = useCallback(
    (text: string) => {
      if (typeof window === "undefined" || !("speechSynthesis" in window)) return;
      window.speechSynthesis.cancel();
      const u = new SpeechSynthesisUtterance(text);
      u.lang = voiceCode;
      u.rate = 0.92;
      const match =
        window.speechSynthesis.getVoices().find((v) => v.lang.replace("_", "-") === voiceCode) ??
        window.speechSynthesis.getVoices().find((v) => v.lang.startsWith(lang));
      if (match) u.voice = match;
      u.onend = () => setSpeaking(false);
      u.onerror = () => setSpeaking(false);
      setSpeaking(true);
      window.speechSynthesis.speak(u);
    },
    [voiceCode, lang],
  );

  useEffect(() => () => stop(), [stop]);

  const value = useMemo(
    () => ({ lang, setLang, t, speak, stop, speaking, voiceCode }),
    [lang, setLang, t, speak, stop, speaking, voiceCode],
  );

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("useI18n must be used inside I18nProvider");
  return ctx;
}
